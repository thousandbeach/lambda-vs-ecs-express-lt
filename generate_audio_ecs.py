OUTPUT_DIR = Path("audio-ecs")
MODEL = "gpt-4o-mini-tts"
VOICE = "onyx"
SPEED = 1.5
INSTRUCTIONS = (
    "落ち着いた男性の声で、テクニカルトークらしく知的な雰囲気で、"
    "やや皮肉っぽい抑揚をつけて読んでください。"
    "句読点では適度に間を取ってください。"
    "「ねん」「やで」「ちゃう」のような関西弁の語尾は、軽い抑揚で自然に。"
)


def main():
    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        print("❌ OPENAI_API_KEY 環境変数がセットされてません")
        print("   export OPENAI_API_KEY='sk-...' を実行してから再度お試しを")
        return

    client = OpenAI(api_key=api_key)
    OUTPUT_DIR.mkdir(exist_ok=True)

    total_chars = sum(len(s) for s in SCRIPTS)
    print(f"🎤 生成開始: {len(SCRIPTS)} スライド / 合計 {total_chars} 文字")
    print(f"   モデル: {MODEL}")
    print(f"   ボイス: {VOICE}")
    print(f"   速度: {SPEED}x")
    print(f"   出力先: {OUTPUT_DIR}/")
    print(f"   推定コスト: 約 ${total_chars * 0.015 / 1000:.3f}")
    print()

    for i, script in enumerate(SCRIPTS, start=1):
        output_path = OUTPUT_DIR / f"slide_{i}.mp3"
        print(f"[{i}/{len(SCRIPTS)}] {len(script)}文字 → {output_path} ...", end=" ", flush=True)

        try:
            response = client.audio.speech.create(
                model=MODEL,
                voice=VOICE,
                input=script,
                speed=SPEED,
                instructions=INSTRUCTIONS,
            )
            response.stream_to_file(output_path)
            print("✅")
        except Exception as e:
            print(f"❌ エラー: {e}")
            return

    print()
    print(f"🎉 完了! {OUTPUT_DIR}/ に {len(SCRIPTS)} ファイル生成")
    print(f"   合計コスト: 約 ${total_chars * 0.015 / 1000:.3f}")


if __name__ == "__main__":
    main()
